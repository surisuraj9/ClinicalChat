"""Export a chat session as a Markdown care summary."""

from __future__ import annotations

import re
import time
from pathlib import Path

from clinicalchat.domain.conversation import ChatSession
from clinicalchat.domain.roles import policy
from clinicalchat.services.patients import PatientDirectory

DISCLAIMER = ("_Generated by ClinicalChat (AI decision support). Not a substitute for professional medical judgement; "
              "verify all findings against the source records._")


def session_markdown(session: ChatSession, patients: PatientDirectory) -> str:
    out = ["# ClinicalChat summary",
           f"- **User:** {session.display_name or session.username} ({policy(session.role).label})",
           f"- **Exported:** {time.strftime('%Y-%m-%d %H:%M')}",
           f"- **Session:** {session.session_id}", ""]
    if not session.turns:
        out.append("_No questions asked yet._")
    for i, t in enumerate(session.turns, 1):
        p = patients.get(t.patient_key)
        out += [f"## {i}. {t.question}", f"_{t.ts} · Patient: {p.label if p else '—'} · Agents: {', '.join(t.agents) or '—'}_", ""]
        if t.blocked:
            out += [f"> 🔒 {t.blocked}", ""]
        if t.safety:
            out += ["### 🛡️ Safety", t.safety, ""]
        for a in t.answers:
            out += [f"### {a['label']}", re.sub(r"</?sub>", "", a["markdown"]), ""]
    out += ["---", DISCLAIMER]
    return "\n".join(out)


class SessionExporter:
    def __init__(self, patients: PatientDirectory, directory: Path):
        self.patients = patients
        self.directory = directory

    def export(self, session: ChatSession) -> Path:
        self.directory.mkdir(parents=True, exist_ok=True)
        path = self.directory / f"clinicalchat-{session.username}-{time.strftime('%Y%m%d-%H%M%S')}.md"
        path.write_text(session_markdown(session, self.patients), encoding="utf-8")
        return path

    def files_of(self, username: str) -> list:
        return list(self.directory.glob(f"clinicalchat-{username}-*.md"))
